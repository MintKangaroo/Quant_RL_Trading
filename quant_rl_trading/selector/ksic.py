"""KSIC 코드를 **상한을 걸 만한 크기의 섹터**로 접는다.

창고의 `sectors`(source=`dart_company`)에 들어 있는 것은 DART 표준산업분류,
즉 한국표준산업분류(KSIC) 코드다. 그런데 그 코드는 세분류·세세분류라
2026-08-21 실측으로 **KR 2,761종목이 535개 코드로 갈렸다** — 최대 군집이
100종목이고 대부분은 한 자리 수다. 이걸 그대로 섹터로 쓰면 상한이 영원히
안 걸린다. 535개짜리 축은 섹터가 아니라 거의 종목 그 자체다.

## 자릿수로 접는다. 표를 만들지 않는다

KSIC 는 대분류(A~U) → 중분류(2자리) → 소분류(3자리) → 세분류(4자리) →
세세분류(5자리) 의 포함관계를 **코드 앞자리로** 표현한다. `KSIC:26410` 도
`KSIC:262` 도 앞 두 자리가 중분류이고, 중분류 번호대가 곧 대분류다. 그래서
535개를 종목별 대응표로 적을 필요가 없다 — 앞 두 자리만 보면 된다.
코드가 바뀌지 않는 한 이 규칙은 종목이 늘어도 그대로 맞는다.

아래 두 표는 종목이 아니라 **분류체계 자체**를 옮겨 적은 것이다(통계청
KSIC 제10차 개정).

## 제조업은 한 단계 더 내린다

대분류만 쓰면 **제조업 C 하나가 1,681종목, 유니버스의 61%** 다(같은 실측).
n_candidates 24 · sector_cap 0.35 이면 상한이 8종목인데, 그 8칸을 반도체와
제약과 자동차가 함께 쓰게 된다. 셋은 같이 움직이지 않는다 — selector.md
§5-5 가 막으려는 것은 **상관된 노출**이지 "제조업 비중" 이 아니다. 그러면
상한은 걸리는데 걸려야 할 곳에 안 걸린다. 예전에 KOSDAQ 소속부로 상한을
걸지 않기로 한 것과 정확히 같은 이유다.

그래서 C 는 통계청이 광공업동태조사에서 쓰는 **중분류군** 아홉으로 나눈다
(10~12 식품, 13~15 섬유, 16~18 목재·종이·인쇄, 19~21 석유·화학·의약,
22~23 고무·플라스틱·비금속, 24~25 금속, 26~28 전자·전기, 29~30 기계·자동차,
31~34 기타). 우리가 지어낸 묶음이 아니라 공표 통계가 쓰는 묶음이다.

## 실측 결과 (2026-08-21, KR 2,761종목)

접고 나면 24개 군집이 되고 그중 **20종목 이상인 것이 17개**, 최대 군집은
전자·전기 525종목(19%)다. 대분류만 쓰면 유의미한 군집이 10개로 줄지만
최대가 61% 라 상한이 사실상 "제조업 대 나머지" 가 된다. 군집 수보다
**최대 군집이 상한 아래로 내려오는 것**이 목적이라 후자를 골랐다.
"""

from __future__ import annotations

from collections.abc import Mapping

#: KSIC 중분류(2자리) 번호대 → 대분류. 통계청 KSIC 제10차 개정.
#: 각 항목은 (시작, 끝, 이름) 이고 양끝을 포함한다.
_DIVISIONS: tuple[tuple[int, int, str], ...] = (
    (1, 3, "농림어업"),
    (5, 8, "광업"),
    # 10~34 는 제조업. `_MANUFACTURING` 이 더 잘게 받는다.
    (35, 35, "전기·가스"),
    (36, 39, "수도·폐기물"),
    (41, 42, "건설"),
    (45, 47, "도소매"),
    (49, 52, "운수·창고"),
    (55, 56, "숙박·음식"),
    (58, 63, "정보통신"),
    (64, 66, "금융·보험"),
    (68, 68, "부동산"),
    (70, 73, "전문·과학·기술"),
    (74, 76, "사업지원·임대"),
    (84, 84, "공공행정"),
    (85, 85, "교육"),
    (86, 87, "보건·복지"),
    (90, 91, "예술·스포츠"),
    (94, 96, "협회·수리·개인서비스"),
    (97, 98, "가구내 고용"),
    (99, 99, "국제·외국기관"),
)

#: 제조업(대분류 C, 중분류 10~34) 안의 중분류군. 통계청 광공업동태조사가
#: 쓰는 묶음이다.
_MANUFACTURING: tuple[tuple[int, int, str], ...] = (
    (10, 12, "제조:식품·음료"),
    (13, 15, "제조:섬유·의복"),
    (16, 18, "제조:목재·종이·인쇄"),
    (19, 21, "제조:석유·화학·의약"),
    (22, 23, "제조:고무·플라스틱·비금속"),
    (24, 25, "제조:금속"),
    (26, 28, "제조:전자·전기"),
    (29, 30, "제조:기계·자동차"),
    (31, 34, "제조:기타"),
)

#: 창고에 적히는 접두사. `collectors` 가 `KSIC:26410` 꼴로 넣는다.
PREFIX = "KSIC:"


def roll_up(code: str) -> str | None:
    """KSIC 코드 하나를 섹터 이름으로. 접을 수 없으면 ``None``.

    **모르는 코드는 "기타" 로 채우지 않는다.** 채우면 서로 아무 상관 없는
    종목들이 한 섹터로 묶여 상한이 엉뚱한 종목을 걸러낸다 —
    `candidates.sector_map` 이 섹터를 모르는 종목을 dict 에서 아예 빼는 것과
    같은 이유다. ``None`` 을 돌려주면 그 종목엔 상한이 안 걸린다.
    """
    text = str(code).strip()
    if text.startswith(PREFIX):
        text = text[len(PREFIX) :]
    if len(text) < 2 or not text[:2].isdigit():
        return None
    division = int(text[:2])
    table = _MANUFACTURING if 10 <= division <= 34 else _DIVISIONS
    for start, end, name in table:
        if start <= division <= end:
            return name
    return None


def roll_up_map(sectors: Mapping[str, str]) -> dict[str, str]:
    """{entity: KSIC 코드} 를 {entity: 섹터} 로. 접히지 않은 종목은 빠진다."""
    rolled = {}
    for entity, code in sectors.items():
        name = roll_up(code)
        if name is not None:
            rolled[str(entity)] = name
    return rolled
