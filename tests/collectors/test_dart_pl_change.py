"""DART 손익구조 변동 파서 — 원문을 줄 단위로 옮긴 것으로 지킨다(2026-09-27 받은 원문의 모양)."""

from __future__ import annotations

from datetime import date

from quant_rl_trading.collectors.dart_pl_change import is_target, parse

#: 원 단위, 개별. 실제 원문(대신정보통신 2026-05-29)의 줄 구조.
PLAIN = "\n".join([
    "매출액 또는 손익구조 30%(대규모법인은 15%)이상 변동",
    "1. 재무제표의 종류", "개별",
    "2. 결산기간", "당해사업연도", "직전사업연도",
    "- 시작일", "2025-04-01", "2024-04-01",
    "- 종료일", "2026-03-31", "2025-03-31",
    "3. 매출액 또는 손익구조변동내용(단위: 원)",
    "당해사업연도", "직전사업연도", "증감금액", "증감비율(%)", "흑자적자전환여부",
    "- 매출액", "259,548,871,126", "202,861,487,817", "56,687,383,309", "27.9", "-",
    "- 영업이익", "15,979,891,214", "9,099,047,769", "6,880,843,445", "75.6", "-",
    "- 당기순이익", "12,580,955,667", "5,738,588,612", "6,842,367,055", "119.2", "-",
    "4. 재무현황(단위 : 원)", "- 자산총계", "143,756,428,973", "135,604,929,009",
])

#: 천원 단위, 연결, 적자전환.
THOUSAND = "\n".join([
    "1. 재무제표의 종류", "연결",
    "2. 결산기간", "- 종료일", "2026-04-30", "2025-10-31",
    "3. 매출액 또는 손익구조 변동내용(단위:천원)",
    "- 매출액", "53,206,197", "52,416,442", "789,755", "1.5", "-",
    "- 영업이익", "-2,144,964", "10,097,939", "-12,242,903", "-", "적자전환",
])


def test_원_단위를_그대로_읽고_증감률은_저장하지_않는다() -> None:
    c = parse(PLAIN)
    assert c is not None and c.usable
    assert c.basis == "separate" and c.unit == 1.0
    assert c.sales_cur == 259_548_871_126 and c.sales_base == 202_861_487_817
    assert c.op_cur == 15_979_891_214 and c.op_base == 9_099_047_769
    assert c.net_cur == 12_580_955_667 and c.net_base == 5_738_588_612
    assert c.op_turn == "" and c.period_end == date(2026, 3, 31)


def test_천원_단위는_원으로_환산하고_전환표지를_읽는다() -> None:
    c = parse(THOUSAND)
    assert c is not None and c.basis == "consolidated"
    assert c.op_cur == -2_144_964e3 and c.op_base == 10_097_939e3
    assert c.op_turn == "적자전환"          # 증감비율 칸이 '-' 여도 전환은 따로 읽는다
    assert c.period_end == date(2026, 4, 30)


def test_단위를_못_읽으면_결측이다() -> None:
    assert parse(PLAIN.replace("(단위: 원)", "").replace("(단위 : 원)", "")) is None


def test_정정공시는_본문이_정정전_표를_이긴다() -> None:
    amended = "\n".join([
        "정정신고(보고)", "4. 정정사항", "정정항목", "정정전", "정정후",
        "3. 매출액 또는 손익구조변동내용(단위: 원)",
        "- 영업이익", "9,000,000,000", "15,979,891,214",   # 정정전 / 정정후
        PLAIN,
    ])
    c = parse(amended)
    assert c is not None and c.op_cur == 15_979_891_214   # 본문(마지막)의 값


def test_자회사_실적은_뺀다() -> None:
    assert is_target("매출액또는손익구조30%(대규모법인은15%)이상변동")
    assert is_target("[기재정정]매출액 또는 손익구조 30%(대규모법인은 15%)이상 변경")
    assert not is_target("매출액또는손익구조30%(대규모법인은15%)이상변경(자회사의 주요경영사항)")
    assert not is_target("영업(잠정)실적(공정공시)")
